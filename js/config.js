window.aplicarProdutosPainelRecuperados = function (catalogo) {
  const VERSAO_RESTAURACAO_PAINEL = 1;
  if (Number(catalogo.versaoRestauracaoPainel) >= VERSAO_RESTAURACAO_PAINEL) return catalogo;
  const recuperados = Array.isArray(window.PRODUTOS_PAINEL_RECUPERADOS)
    ? window.PRODUTOS_PAINEL_RECUPERADOS
    : [];
  const produtos = [...(Array.isArray(catalogo.produtos) ? catalogo.produtos : [])];
  recuperados.forEach((produtoRecuperado) => {
    const indice = produtos.findIndex((produto) => String(produto.id) === String(produtoRecuperado.id));
    if (indice === -1) {
      produtos.push(structuredClone(produtoRecuperado));
      return;
    }
    produtos[indice] = { ...produtos[indice], ...structuredClone(produtoRecuperado) };
  });
  return { ...catalogo, produtos, versaoRestauracaoPainel: VERSAO_RESTAURACAO_PAINEL };
};

window.LOJA_PADRAO = window.aplicarProdutosPainelRecuperados(window.LOJA_PADRAO);

